/** Reads and updates KEY=VALUE lines in the local .env, backing it up before any change. */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const ROOT = resolve(import.meta.dirname, '..', '..');
export const ENV_FILE = join(ROOT, '.env');
const LOCAL_DIR = join(ROOT, '.local');

export function readEnvFile(): Map<string, string> {
  const entries = new Map<string, string>();
  if (!existsSync(ENV_FILE)) return entries;
  for (const line of readFileSync(ENV_FILE, 'utf8').split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (match?.[1] !== undefined && match[2] !== undefined) entries.set(match[1], match[2]);
  }
  return entries;
}

/** Sets the given keys, keeps every other line, and backs the old file up to .local/. */
export function writeEnvKeys(values: Record<string, string>): void {
  const lines = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8').split(/\r?\n/) : [];
  if (existsSync(ENV_FILE)) {
    mkdirSync(LOCAL_DIR, { recursive: true });
    const backup = join(LOCAL_DIR, `env-backup-${new Date().toISOString().replace(/[:.]/g, '-')}.txt`);
    copyFileSync(ENV_FILE, backup);
    console.log(`Backed up the previous .env to ${backup}.`);
  } else {
    lines.push(`# Generated by the ProcureFlow local scripts on ${new Date().toISOString()}. Never commit this file.`);
  }
  const pending = new Map(Object.entries(values));
  const updated = lines.map((line) => {
    const key = /^([A-Z0-9_]+)=/.exec(line)?.[1];
    if (key === undefined || !pending.has(key)) return line;
    const value = pending.get(key);
    pending.delete(key);
    return `${key}=${value}`;
  });
  while (updated.length > 0 && updated.at(-1) === '') updated.pop();
  for (const [key, value] of pending) updated.push(`${key}=${value}`);
  writeFileSync(ENV_FILE, `${updated.join('\n')}\n`, { mode: 0o600 });
}
